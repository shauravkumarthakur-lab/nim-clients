import { requireCtx } from "@/lib/tenant";
import { PageHeader, Note } from "@/components/ui/misc";
import { Card, CardBody, CardHeader } from "@/components/ui/card";
import { ConfirmAction } from "@/components/ui/form-dialog";
import { SettingsTabs } from "../tabs";
import { resetDemo } from "../actions";

export const metadata = { title: "Demo data" };

export default async function DemoPage() {
  const ctx = await requireCtx("MANAGE_ORG");
  return (
    <>
      <PageHeader title="Settings" description="Demo data" />
      <SettingsTabs active="demo" />
      <Card className="max-w-2xl">
        <CardHeader title="Demo organisation" />
        <CardBody className="flex flex-col gap-4 text-sm">
          {ctx.org.isDemo ? (
            <>
              <p>This is the <b>demo workspace</b>. Every client, person and number in it is fictional and generated by MarginOS. It lives in its own organisation and never mixes with real workspaces.</p>
              <p className="text-muted">Resetting deletes everything in this demo workspace (including changes you made while exploring) and regenerates ~3.5 months of fresh demo data relative to today.</p>
              <div><ConfirmAction action={resetDemo} payload={{ confirm: "RESET" }} label="Reset demo data" icon="none" variant="danger" size="md" testId="reset-demo"
                title="Reset the demo workspace?" description="All demo records will be deleted and regenerated. This cannot be undone." confirmLabel="Reset demo" /></div>
            </>
          ) : (
            <Note>This is a real workspace. MarginOS never inserts demo or sample data into real workspaces, and reset is unavailable here. To explore with demo data, sign out and choose “Open demo workspace”.</Note>
          )}
        </CardBody>
      </Card>
    </>
  );
}
